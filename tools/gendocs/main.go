// Command gendocs writes the generated reference pages: one Markdown page
// per CLI command (via cobra/doc) and the sarifix.yaml reference built from
// the config structs' doc tags, so the docs never drift from the code.
//
// Usage: go run ./tools/gendocs [-out docs/reference]
package main

import (
	"bytes"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"reflect"
	"strings"

	"github.com/spf13/cobra/doc"

	"github.com/rossedman/sarifix/internal/cli"
	"github.com/rossedman/sarifix/pkg/config"
)

// main parses flags and writes the pages.
func main() {
	os.Exit(run(os.Args[1:], os.Stderr))
}

// run writes every reference page under the -out directory.
func run(args []string, stderr io.Writer) int {
	fs := flag.NewFlagSet("gendocs", flag.ContinueOnError)
	fs.SetOutput(stderr)
	out := fs.String("out", filepath.Join("docs", "reference"), "output directory")
	if err := fs.Parse(args); err != nil {
		return 2
	}
	if err := commands(filepath.Join(*out, "commands")); err != nil {
		_, _ = fmt.Fprintln(stderr, "gendocs:", err)
		return 1
	}
	if err := os.WriteFile(filepath.Join(*out, "config.md"), []byte(configReference()), 0o644); err != nil { //nolint:gosec // docs are public
		_, _ = fmt.Fprintln(stderr, "gendocs:", err)
		return 1
	}
	return 0
}

// commands regenerates one page per command, removing stale pages first.
func commands(dir string) error {
	if err := os.RemoveAll(dir); err != nil {
		return err
	}
	if err := os.MkdirAll(dir, 0o755); err != nil { //nolint:gosec // docs are public
		return err
	}
	root := cli.NewRoot(io.Discard, io.Discard)
	root.DisableAutoGenTag = true
	prepender := func(name string) string {
		title := strings.ReplaceAll(strings.TrimSuffix(filepath.Base(name), ".md"), "_", " ")
		return "---\ntitle: " + title + "\n---\n\n<!-- Generated by tools/gendocs. Do not edit. -->\n\n"
	}
	link := func(name string) string { return name }
	return doc.GenMarkdownTreeCustom(root, dir, prepender, link)
}

// configReference renders the sarifix.yaml field reference.
func configReference() string {
	var b bytes.Buffer
	b.WriteString("---\ntitle: sarifix.yaml reference\n---\n\n<!-- Generated by tools/gendocs from pkg/config. Do not edit. -->\n\n")
	b.WriteString("# sarifix.yaml reference\n\n")
	b.WriteString("Every key sarifix reads from `sarifix.yaml`, generated from the config schema. ")
	b.WriteString("Unknown keys are an error. See [Configuration](../configuration.md) for a guided tour.\n")
	writeStruct(&b, reflect.TypeFor[config.Config](), "", 2)
	return b.String()
}

// writeStruct writes a table of t's fields, then a section per nested struct.
func writeStruct(b *bytes.Buffer, t reflect.Type, prefix string, depth int) {
	type nested struct {
		key string
		t   reflect.Type
		doc string
	}
	var subs []nested
	b.WriteString("\n| Key | Type | Default | Description |\n| --- | --- | --- | --- |\n")
	for f := range t.Fields() {
		key := strings.Split(f.Tag.Get("yaml"), ",")[0]
		if key == "" || key == "-" {
			continue
		}
		full := key
		if prefix != "" {
			full = prefix + "." + key
		}
		def := f.Tag.Get("default")
		if f.Tag.Get("required") == "true" {
			def = "required"
		}
		if def == "" {
			def = "none"
		}
		fmt.Fprintf(b, "| `%s` | %s | %s | %s |\n", full, typeName(f.Type), code(def), f.Tag.Get("doc"))
		if el := elem(f.Type); el.Kind() == reflect.Struct && el != reflect.TypeFor[config.Duration]() {
			k := full
			if f.Type.Kind() == reflect.Slice {
				k += "[]"
			}
			subs = append(subs, nested{k, el, f.Tag.Get("doc")})
		}
	}
	for _, s := range subs {
		fmt.Fprintf(b, "\n%s `%s`\n\n%s\n", strings.Repeat("#", depth), s.key, s.doc)
		writeStruct(b, s.t, s.key, depth+1)
	}
}

// elem unwraps slices to their element type.
func elem(t reflect.Type) reflect.Type {
	if t.Kind() == reflect.Slice {
		return elem(t.Elem())
	}
	return t
}

// typeName describes a field type in YAML terms.
func typeName(t reflect.Type) string {
	switch {
	case t == reflect.TypeFor[config.Duration]():
		return "duration"
	case t.Kind() == reflect.Slice:
		return "list of " + typeName(t.Elem())
	case t.Kind() == reflect.Map:
		return "map of " + typeName(t.Elem())
	case t.Kind() == reflect.Struct:
		return "object"
	case t.Kind() == reflect.Bool:
		return "bool"
	case t.Kind() == reflect.Int:
		return "int"
	}
	return "string"
}

// code wraps a default value in backticks unless it is a word like none.
func code(s string) string {
	if s == "none" || s == "required" {
		return s
	}
	return "`" + s + "`"
}
